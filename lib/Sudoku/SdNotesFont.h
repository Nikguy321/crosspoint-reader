#pragma once

// Sudoku notes: 7x11 px digits 1-9 for the pencil marks (a 3x3 of them per 49 px square, at
// SdLayout's NOTE_X / NOTE_Y). 2 px vertical stems and 1 px bars, about a phone's note size
// (0.8 x 1.3 mm on the panel). 99 bytes. Each row is 7 bits, bit 6 = the leftmost column.
// Crossword's 5x7 CwDigits are the fallback if these read badly on the panel.

#include <cstdint>

namespace sd {

constexpr int NOTE_DIGIT_W = 7;
constexpr int NOTE_DIGIT_H = 11;

constexpr uint8_t NOTE_DIGITS_7X11[9][NOTE_DIGIT_H] = {
    {0x0C, 0x1C, 0x3C, 0x0C, 0x0C, 0x0C, 0x0C, 0x0C, 0x0C, 0x0C, 0x3F},  // 1
    {0x3E, 0x63, 0x03, 0x03, 0x06, 0x0C, 0x18, 0x30, 0x60, 0x60, 0x7F},  // 2
    {0x3E, 0x63, 0x03, 0x03, 0x1E, 0x03, 0x03, 0x03, 0x03, 0x63, 0x3E},  // 3
    {0x06, 0x0E, 0x1E, 0x36, 0x66, 0x66, 0x7F, 0x06, 0x06, 0x06, 0x06},  // 4
    {0x7F, 0x60, 0x60, 0x60, 0x7E, 0x03, 0x03, 0x03, 0x03, 0x63, 0x3E},  // 5
    {0x1E, 0x30, 0x60, 0x60, 0x7E, 0x63, 0x63, 0x63, 0x63, 0x63, 0x3E},  // 6
    {0x7F, 0x03, 0x03, 0x06, 0x06, 0x0C, 0x0C, 0x18, 0x18, 0x18, 0x18},  // 7
    {0x3E, 0x63, 0x63, 0x63, 0x3E, 0x63, 0x63, 0x63, 0x63, 0x63, 0x3E},  // 8
    {0x3E, 0x63, 0x63, 0x63, 0x63, 0x3F, 0x03, 0x03, 0x03, 0x06, 0x3C},  // 9
};

// Ink at (x, y) of digit d (1..9), x 0..6 left to right, y 0..10 top to bottom.
constexpr bool notePixel(const int d, const int x, const int y) {
  return d >= 1 && d <= 9 && x >= 0 && x < NOTE_DIGIT_W && y >= 0 && y < NOTE_DIGIT_H &&
         ((NOTE_DIGITS_7X11[d - 1][y] >> (NOTE_DIGIT_W - 1 - x)) & 1) != 0;
}

}  // namespace sd
